sim.k         = 1;                                  % number of simulation shots
sim.t         = 0;                                  % simulation time

% initial state and system information
p_x    = -2.0;  % x-axis position, meter
p_y    =  1.0;  % y-axis position, meter
v_x    = 0;     % x-axis velocity, meter/sec
v_y    = 0;     % y-axis velocity, meter/sec
theta  = 0;     % roll angle that the aircraft makes with the horizon, rad
omega  = 0;     % roll angular velocity, rad/sec
u1     = 9.8;   % control input u_1 and \dot{u}_1, which are the state 
du1    = 0;     % generated by dynamic feedback linearization
x      = [p_x; p_y; v_x; v_y; theta; omega; u1; du1]; % combined state
