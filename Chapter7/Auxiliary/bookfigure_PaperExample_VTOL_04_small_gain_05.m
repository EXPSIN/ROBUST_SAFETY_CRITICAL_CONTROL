    x_info_2 = model_info(x_2);

    % draw the graphics
    H  = graphic(H, x_info, ctrl, sim);
    H2 = graphic2(H2, x_info_2, ctrl_2, sim);
    % fprintf('%.1f sec\n', sim.t);
    drawnow limitrate;
    k/ sim.steps
