        phi_2 = k_phi*max(c_A_c - A_L*A', 0);
        phi   = min(phi_1 + phi_2, [], 2);
        b_L   = A_L*u_L + phi;
    end

[ctrl.x2_ref, fval, exitflag, output, lambda] = quadprog(eye(2), ...
    -ctrl.x2_nominal, ctrl.A_L, ctrl.b_L, [], [], [], [], zeros(2,1), opt);

    if(exitflag == -2)
