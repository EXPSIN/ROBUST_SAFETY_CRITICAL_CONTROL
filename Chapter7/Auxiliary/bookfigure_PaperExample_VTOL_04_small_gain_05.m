    ctrl   = controller(x_info, sim.t);
    % x_info_2 = model_info(x_2);
    ctrl_2 = controller2(x_info_2, sim.t);

    % simulation in decentralized way
    % [~, x_ode]   = ode15s(@(t, x)VTOL_dynamics(x, ctrl), sim.t+[0, sim.step_time], x);
